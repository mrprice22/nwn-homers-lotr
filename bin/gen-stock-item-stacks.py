#!/usr/bin/env python3
"""Build tests/stock_item_stacks.json — stock item resref -> StackSize.

tests/check_divergent_stores.py needs to know what stack a `.utm` entry would
hand out. For a module item that is the local `.uti`'s StackSize; for a stock
item (CEP / base game, living in the install's BIF archives) there is no file in
`unpacked/` to read. Assuming 1 is wrong and produced 21 false divergences on
the first run: stock ammunition ships at 99 (`nw_wammar001`, the whole
`nw_wamm*` family) and throwing weapons at 50 (`nw_wthdt001`), which is exactly
what the placements sell.

A build gate must not depend on a local NWN install, so the answer is a small
committed table: only resrefs whose StackSize is not 1 are recorded (a few
hundred out of ~2700), and everything absent is 1.

Re-run after a Beamdog patch that changes item blueprints:

    python3 bin/gen-stock-item-stacks.py [--nwn /path/to/nwn]

Reads the KEY/BIF archives with the same parser nwn-wiki uses for stock item
names (bin/wiki_data/build_stock_item_names.py in the nwn_manager repo).
"""

import argparse
import json
import os
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "stock_item_stacks.json"
DEFAULT_NWN = Path.home() / ".local/share/Steam/steamapps/common/Neverwinter Nights"
WIKI_DATA = Path.home() / "GIT/nwn_manager/bin/wiki_data"


def gff_stack_size(data):
    """StackSize out of a GFF V3.2 blob, or None. Top-level WORD field."""
    if data[:4] not in (b"UTI ", b"BIC ", b"GFF "):
        pass  # file type varies; the header layout below is the same regardless
    try:
        so, sc, fo, fc, lo, lc, fdo, fdc = struct.unpack_from("<8I", data, 8)
        labels = [data[lo + 16 * i:lo + 16 * i + 16].rstrip(b"\0").decode("latin1")
                  for i in range(lc)]
        for i in range(fc):
            _t, li, dv = struct.unpack_from("<III", data, fo + 12 * i)
            if labels[li] == "StackSize":
                return dv
    except (struct.error, IndexError, UnicodeDecodeError):
        return None
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nwn", type=Path, default=DEFAULT_NWN,
                    help=f"NWN install root (default: {DEFAULT_NWN})")
    args = ap.parse_args()

    sys.path.insert(0, str(WIKI_DATA))
    try:
        import build_stock_item_names as B
    except ImportError:
        print(f"error: cannot import the KEY/BIF reader from {WIKI_DATA} "
              "(nwn_manager repo)", file=sys.stderr)
        return 2

    keys = sorted((args.nwn / "data").glob("*.key"))
    if not keys:
        print(f"error: no .key archives under {args.nwn / 'data'}", file=sys.stderr)
        return 2

    index = {}
    for k in keys:
        index.update(B._parse_nwn_key(k))

    stacks = {}
    for resref in sorted(index):
        bif, var = index[resref]
        size = gff_stack_size(B._read_bif_entry(bif, var))
        if size and size != 1:
            stacks[resref] = size

    OUT.write_text(json.dumps({
        "_comment": ("Stock (CEP / base game) item resref -> StackSize, for items "
                     "that do not ship at 1. Generated by bin/gen-stock-item-stacks.py; "
                     "consumed by tests/check_divergent_stores.py. Anything absent is 1."),
        "_source": [k.name for k in keys],
        "stacks": stacks,
    }, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(stacks)} stock item(s) with a "
          f"non-1 stack, out of {len(index)} scanned")
    return 0


if __name__ == "__main__":
    sys.exit(main())
