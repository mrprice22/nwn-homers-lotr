KIND_LIST = {"door": "Door List", "trigger": "TriggerList",
             "use": "Placeable List"}
KIND_POS = {"door": door_pos, "trigger": trigger_pos, "use": placeable_pos}

RESULTS = ("added", "updated", "unchanged", "dropped", "dup-skip",
           "manual-skip", "manual-fix", "manual-mismatch", "exempt")


class ScanResult:
    """Everything one pass over the module found. Nothing is written: call
    .save() (or gen-map-notes --apply) to persist the buffered edits."""

    def __init__(self):
        self.stats = {k: 0 for k in RESULTS}
        self.log = []            # (area, cls, kind, label, text, result)
        self.editors = {}
        self.missing_src = []    # (area, kind, label, to_name) object not found
        self.dup_tag = []        # (area, kind, label, why, dests) ambiguous tag
        self.mismatches = []     # (area, label, dest) hand note disagrees
        self.dropped = []        # (area, tag, text, kept_tag, metres) pin removed
        self.exempt = []         # (area, kind, label, dest) @nomapnote
        self.uncovered = []      # (area, kind, label, dest) NO pin -> gate fails
        self.renamed = []        # (area, label, text) @mapnote override in force

    @property
    def desynced(self):
        return [e.resref for e in self.editors.values() if e.desync]

    def save(self):
        for e in self.editors.values():
            e.save()


def graph_is_stale():
    """Areas that exist in unpacked/ but not in the graph.

    The graph is a wiki artefact and this tool is not allowed to rebuild it, so
    a builder who adds an area and repacks before the daily refresh has a graph
    that cannot see it yet, and must be warned rather than blocked.

    Deliberately NOT an mtime comparison: a git checkout or an `nwn-manager
    unpack` restamps every file in unpacked/, and --apply restamps them itself,
    so mtime would report "stale" constantly - including immediately after this
    tool had just brought the tree fully up to date, which would quietly disarm
    the build gate. Comparing the area sets asks the question we actually mean.
    """
    try:
        known = set(load(GRAPH)["areas"])
    except (OSError, KeyError, ValueError):
        return []
    here = {p.name[:-len(".are.json")] for p in UNPACKED.glob("*.are.json")}
    return sorted(here - known)


def scan(update_manual=False):
    """One full pass. Buffers edits in AreaEditors without writing anything."""
    graph = load(GRAPH)["areas"]
    tele = teleport_scripts()
    res = ScanResult()

    def ed(resref):
        if resref not in res.editors:
            res.editors[resref] = AreaEditor(resref)
        return res.editors[resref]

    def area_exists(resref):
        """The graph can outlive an area that has since been deleted."""
        return (UNPACKED / f"{resref}.git.json").exists()

    def record(area, cls, kind, label, text, r):
        res.stats[r] += 1
        res.log.append((area, cls, kind, label, text, r))

    # ---- Pass A: door / trigger / use -> destination note --------------- #
    for area in sorted(graph):
        info = graph[area]
        edges = [t for t in info.get("transitions", [])
                 if t["kind"] in KIND_LIST]
        if not edges or not area_exists(area):
            continue
        e = ed(area)
        git_items = {k: gv(e.git.get(v)) or [] for k, v in KIND_LIST.items()}
        # group edges by (kind, label); an object whose tag serves several
        # distinct destinations is ambiguous (e.g. the Gwathdor maze / Well of
        # Eru "AreaTransition" triggers) -- we can't tell which pin means what,
        # so skip it rather than mislabel.
        groups = {}
        for t in edges:
            groups.setdefault((t["kind"], t.get("label") or ""), set()).add(
                t.get("to_name") or t.get("to") or "?")
        for (kind, label), dests in sorted(groups.items()):
            objs = by_tag(git_items[kind], label)
            if not objs:
                for d in dests:
                    res.missing_src.append((area, kind, label, d))
                continue
            if len(dests) > 1:
                res.dup_tag.append((area, kind, label, "multi-dest",
                                    sorted(dests)))
                continue
            dest = next(iter(dests))
            # one note per source object (same-tag doors sit at different spots)
            for i, (idx, obj) in enumerate(objs):
                suffix = label if len(objs) == 1 else f"{label}_{i}"
                tag = sanitize_tag(XFER_PREFIX, suffix)
                suppress, override = directives(
                    e.obj_comment(KIND_LIST[kind], idx))
                if suppress:
                    e.drop_auto(tag, "@nomapnote")
                    res.exempt.append((area, kind, label, dest))
                    record(area, "xfer", kind, label, dest, "exempt")
                    continue
                # area names carry stray whitespace ("Bank of Bree ") often
                # enough to be worth trimming; colour codes are LEFT ALONE --
                # <c..> is NWN's own markup and renders as colour on the pin
                text = (override or dest).strip()
                if override:
                    res.renamed.append((area, label, override))
                x, y, z = KIND_POS[kind](obj)
                r = e.upsert(tag, text, x, y, z, update_manual)
                record(area, "xfer", kind, label, text, r)
                if r == "manual-mismatch":
                    res.mismatches.append((area, label, text))
                elif r == "added":
                    # the pin does not exist in the tree yet -> the gate's
                    # offender list, cleared by --apply
                    res.uncovered.append((area, kind, label, text))

    # ---- Pass B: talk teleporter NPCs -> one POI note each -------------- #
    talk_areas = sorted({a for a, info in graph.items()
                         if any(t["kind"] == "talk"
                                for t in info.get("transitions", []))
                         and area_exists(a)})
    for area in talk_areas:
        e = ed(area)
        creatures = gv(e.git.get("Creature List")) or []
        placed = set()
        for idx, c in enumerate(creatures):
            conv = gv(c.get("Conversation"))
            if not conv or not (dlg_scripts(conv) & tele):
                continue
            name = creature_name(c)
            if name in placed:
                continue
            placed.add(name)
            tag = sanitize_tag(POI_PREFIX, gv(c.get("Tag")) or name)
            suppress, override = directives(e.obj_comment("Creature List", idx))
            if suppress:
                e.drop_auto(tag, "@nomapnote")
                res.exempt.append((area, "talk", gv(c.get("Tag")), name))
                record(area, "poi", "talk", gv(c.get("Tag")), name, "exempt")
                continue
            text = (override or name).strip()
            if override:
                res.renamed.append((area, gv(c.get("Tag")), override))
            x, y, z = creature_pos(c)
            r = e.upsert(tag, text, x, y, z, update_manual)
            record(area, "poi", "talk", gv(c.get("Tag")), text, r)

    # every pin that went, collected from the editors themselves so the report
    # is the truth about what was removed rather than a re-derivation
    for area in sorted(res.editors):
        for gone, text, kept, metres in res.editors[area].removed:
            res.dropped.append((area, gone, text, kept, metres))
    res.stats["dropped"] = len(res.dropped)

    return res


def dead_links():
    """Placed transitions whose LinkedTo tag exists NOWHERE in the module.

    These lead nowhere in game, so they can never carry a meaningful pin. Report
    only -- deliberately not a gate, and not this tool's job to fix.
    """
    tags = set()
    gits = {}
    for p in sorted(UNPACKED.glob("*.git.json")):
        d = load(p)
        gits[p.name[:-len(".git.json")]] = d
        for key, val in d.items():
            if not isinstance(val, dict) or val.get("type") != "list":
                continue
            for o in val["value"]:
                t = gv(o.get("Tag"))
                if t:
                    tags.add(t.casefold())
    out = []
    for area, d in gits.items():
        for key in KIND_LIST.values():
            for o in gv(d.get(key)) or []:
                lt = (gv(o.get("LinkedTo")) or "").strip()
                if lt and lt.casefold() not in tags:
                    out.append((area, key, gv(o.get("Tag")) or "?", lt))
    return sorted(out)


