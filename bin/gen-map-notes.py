# main
# --------------------------------------------------------------------------- #
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apply", action="store_true",
                    help="write .git/.gic edits (default: dry-run report)")
    ap.add_argument("--update-manual", action="store_true",
                    help="also rewrite hand-placed notes whose text disagrees")
    ap.add_argument("--verbose", action="store_true",
                    help="list every note action, not just the summary")
    ap.add_argument("--no-dead-links", action="store_true",
                    help="skip the broken-transition report (reads every .git)")
    args = ap.parse_args()

    if not GRAPH.exists():
        sys.exit(f"missing {GRAPH} -- run the wiki once to build module-index/")
    res = scan(update_manual=args.update_manual)

    if args.verbose:
        for area, cls, kind, label, text, r in res.log:
            print(f"  [{r:14}] {area:22} {cls} {kind:7} {label!r:24} -> {text!r}")
        print()

    print("=== gen-map-notes summary "
          f"({'APPLY' if args.apply else 'DRY-RUN'}) ===")
    for k in RESULTS:
        print(f"  {k:16} {res.stats[k]}")
    print(f"  areas touched     {sum(1 for e in res.editors.values() if e.dirty)}")

    if res.uncovered:
        print(f"\n-- transitions with NO map note ({len(res.uncovered)}) "
              f"[the build gate fails on these until --apply]:")
        for area, kind, label, dest in res.uncovered:
            print(f"     {area:22} {kind:7} {label!r:24} -> {dest!r}")
    if res.dropped:
        print(f"\n-- pins removed ({len(res.dropped)}) [a duplicate reading the "
              f"same text within {MANUAL_RADIUS:.0f}m, or @nomapnote]:")
        for area, tag, text, kept, metres in res.dropped:
            why = kept if kept.startswith("@") else f"kept {kept} ({metres:.1f}m)"
            print(f"     {area:22} {tag:30} {text!r:34} {why}")
    if res.renamed:
        print(f"\n-- @mapnote label overrides in force ({len(res.renamed)}):")
        for area, label, text in res.renamed:
            print(f"     {area:22} {label!r:24} -> {text!r}")
    if res.exempt:
        print(f"\n-- @nomapnote transitions ({len(res.exempt)}) "
              f"[deliberately unlabelled; the gate does not ask for these]:")
        for area, kind, label, dest in res.exempt:
            print(f"     {area:22} {kind:7} {label!r:24} -> {dest!r}")
    if res.missing_src:
        print(f"\n-- transitions with no source object in the area "
              f"({len(res.missing_src)}) [dead/renamed link; no note added]:")
        for area, kind, label, dest in res.missing_src[:40]:
            print(f"     {area:22} {kind:7} {label!r:24} -> {dest!r}")
        if len(res.missing_src) > 40:
            print(f"     ... and {len(res.missing_src) - 40} more")
    if res.dup_tag:
        print(f"\n-- ambiguous source tags ({len(res.dup_tag)}) "
              f"[one tag -> several destinations; skipped, no note]:")
        for area, kind, label, _why, dests in res.dup_tag:
            print(f"     {area:22} {kind:7} {label!r:18} -> {dests}")
    if res.mismatches:
        print(f"\n-- manual notes disagreeing with destination "
              f"({len(res.mismatches)}) [left as-is; use --update-manual]:")
        for area, label, dest in res.mismatches:
            print(f"     {area:22} {label!r:24} should read {dest!r}")

    if not args.no_dead_links:
        dead = dead_links()
        if dead:
            print(f"\n-- BROKEN transitions ({len(dead)}) [LinkedTo names a tag "
                  f"that exists nowhere; leads nowhere in game, cannot be "
                  f"pinned]:")
            for area, key, tag, lt in dead:
                print(f"     {area:22} {key:16} {tag!r:30} -> {lt!r}")

    if res.desynced:
        print(f"\n-- WARNING: pre-existing .git/.gic WaypointList length mismatch "
              f"in: {', '.join(res.desynced)}")
        print("   (appended notes keep counts balanced; the prior offset is "
              "untouched)")
    unseen = graph_is_stale()
    if unseen:
        print(f"\n-- WARNING: {GRAPH.name} predates {len(unseen)} area(s) in "
              f"unpacked/ -- their transitions are invisible here until the "
              f"wiki is rebuilt: {', '.join(unseen[:8])}"
              + (" ..." if len(unseen) > 8 else ""))

    if args.apply:
        res.save()
        print("\nwrote changes.")
    else:
        print("\n(dry-run -- pass --apply to write)")


if __name__ == "__main__":
    main()
