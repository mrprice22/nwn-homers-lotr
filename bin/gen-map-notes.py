class AreaEditor:
    """Buffers note additions/updates for one area's .git + .gic pair."""

    def __init__(self, resref):
        self.resref = resref
        self.git_path = UNPACKED / f"{resref}.git.json"
        self.gic_path = UNPACKED / f"{resref}.gic.json"
        self.git = load(self.git_path)
        self.gic = load(self.gic_path)
        self.wl = gv(self.git.setdefault(
            "WaypointList", {"type": "list", "value": []}))
        self.gwl = gv(self.gic.setdefault(
            "WaypointList", {"type": "list", "value": []}))
        self.dirty = False
        self.desync = len(self.wl) != len(self.gwl)
        self.removed = []   # (gone_tag, text, kept_tag_or_reason, metres)
        # index existing auto notes by their deterministic tag
        self.auto = {gv(w.get("Tag")): w for w in self.wl if is_auto(w)}
        self.manual = [w for w in self.wl if has_note(w) and not is_auto(w)]

    def obj_comment(self, list_key, index):
        """The toolset Comment of the <list_key>[index] object in this area.

        .git and .gic lists are positional/parallel; if they have drifted out of
        step we cannot trust the index, so read nothing rather than the wrong
        object's directives.
        """
        git_list = gv(self.git.get(list_key)) or []
        gic_list = gv(self.gic.get(list_key)) or []
        if len(git_list) != len(gic_list) or index >= len(gic_list):
            return ""
        return gv(gic_list[index].get("Comment")) or ""

    def manual_cover(self, x, y):
        for w in self.manual:
            mx, my = note_pos(w)
            if dist(x, y, mx, my) <= MANUAL_RADIUS:
                return w
        return None

    def dup_cover(self, text, x, y, ignore=None):
        """An existing pin reading the same text close enough to be a visible
        duplicate. Considers hand-placed AND auto pins; `ignore` skips the pin
        being tested itself."""
        key = (text or "").strip().casefold()
        if not key:
            return None
        for w in self.wl:
            if w is ignore or not has_note(w):
                continue
            if (note_text(w) or "").strip().casefold() != key:
                continue
            wx, wy = note_pos(w)
            if dist(x, y, wx, wy) <= MANUAL_RADIUS:
                return w
        return None

    def remove_note(self, note):
        """Delete a pin and its index-parallel .gic comment struct."""
        try:
            i = self.wl.index(note)
        except ValueError:
            return False
        # only touch .gic when the two lists are in step, else we would delete
        # an unrelated object's comment and deepen the drift
        if not self.desync and i < len(self.gwl):
            del self.gwl[i]
        del self.wl[i]
        self.auto.pop(gv(note.get("Tag")), None)
        if note in self.manual:
            self.manual.remove(note)
        self.dirty = True
        return True

    def drop_auto(self, tag, reason):
        """Remove an auto pin by tag (used by @nomapnote). True if one went."""
        cur = self.auto.get(tag)
        if cur is None:
            return False
        self.removed.append((tag, note_text(cur), reason, 0.0))
        return self.remove_note(cur)

    def upsert(self, tag, text, x, y, z, update_manual):
        """Returns one of: 'added', 'updated', 'unchanged', 'dropped',
        'dup-skip', 'manual-skip', 'manual-fix', 'manual-mismatch'."""
        cur = self.auto.get(tag)
        if cur is not None:
            # a pin a previous run created that now duplicates a neighbour
            dup = self.dup_cover(text, x, y, ignore=cur)
            if dup is not None:
                # a hand-placed pin always outranks ours; between two auto pins
                # the lower-sorting tag stays, so which one survives doesn't
                # depend on the order the graph happens to hand them to us
                drop_other = is_auto(dup) and (gv(dup.get("Tag")) or "") > tag
                gone, kept = (dup, cur) if drop_other else (cur, dup)
                self.removed.append((
                    gv(gone.get("Tag")), text, gv(kept.get("Tag")),
                    dist(*note_pos(gone), *note_pos(kept))))
                self.remove_note(gone)
                if not drop_other:
                    return "dropped"
                # cur survives -- fall through and refresh it as usual
            # position compares with a tolerance, never for equality -- see
            # POS_EPSILON for why exact comparison churned every trigger pin
            cx = gv(cur.get("XPosition")) or 0.0
            cy = gv(cur.get("YPosition")) or 0.0
            changed = (note_text(cur) != text
                       or dist(cx, cy, x, y) > POS_EPSILON)
            if changed:
                cur["MapNote"]["value"] = {"0": text}
                cur["XPosition"]["value"] = round(x, 5)
                cur["YPosition"]["value"] = round(y, 5)
                self.dirty = True
                return "updated"
            return "unchanged"
        # nothing of ours here yet: don't add a second pin reading what a pin
        # already within MANUAL_RADIUS reads
        if self.dup_cover(text, x, y) is not None:
            return "dup-skip"
        man = self.manual_cover(x, y)
        if man is not None:
            if note_text(man) == text:
                return "manual-skip"
            if update_manual:
                man["MapNote"]["value"] = {"0": text}
                if gv(man.get("HasMapNote")) != 1:
                    man["HasMapNote"]["value"] = 1
                if gv(man.get("MapNoteEnabled")) != 1:
                    man.setdefault("MapNoteEnabled",
                                   {"type": "byte", "value": 1})["value"] = 1
                self.dirty = True
                return "manual-fix"
            return "manual-mismatch"
        note = make_note(tag, text, x, y, z)
        self.wl.append(note)
        self.gwl.append(gic_comment())
        self.auto[tag] = note
        self.dirty = True
        return "added"

    def save(self):
        if self.dirty:
            dump(self.git_path, self.git)
            dump(self.gic_path, self.gic)


def teleport_scripts():
    out = set()
    for nss in UNPACKED.glob("*.nss"):
        try:
            if JUMP_RE.search(nss.read_text(encoding="utf-8", errors="ignore")):
                out.add(nss.stem)
        except OSError:
            pass
    return out


def dlg_scripts(conv):
    p = UNPACKED / f"{conv}.dlg.json"
    if not p.exists():
        return set()
    d = load(p)
    out = set()
    for key in ("EntryList", "ReplyList"):
        for n in gv(d.get(key)) or []:
            s = gv(n.get("Script"))
            if s:
                out.add(s)
    return out


def creature_name(c):
    name = locstr(c.get("FirstName")).strip()
    last = locstr(c.get("LastName")).strip()
    if name and last:
        name = f"{name} {last}"
    if not name:
        bp = UNPACKED / f"{gv(c.get('TemplateResRef'))}.utc.json"
        if bp.exists():
            d = load(bp)
            name = (locstr(d.get("FirstName")) + " "
                    + locstr(d.get("LastName"))).strip()
    return name or gv(c.get("Tag")) or "NPC"




