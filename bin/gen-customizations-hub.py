def json_for_script(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


def render_hub(pages: list[Page], amap: dict[str, str]) -> str:
    texts: list[str] = []
    out: list[str] = []
    for p in pages:
        base = f"Customizations/{p.href}"
        cards = []
        for s in p.sections:
            texts.append(s.text if s.id else f"{s.title} {s.text}")
            idattr = f' id="{s.id}"' if s.id else ""
            href = f"{base}#{s.id}" if s.id else base
            subs = ""
            if s.subs:
                subs = ('\n    <p class="cz-sub">Also: ' + " &middot; ".join(
                    f'<a id="{sid}" href="{base}#{sid}">{html.escape(st)}</a>'
                    for sid, st in s.subs) + "</p>")
            stray = "".join(f'<span id="{i}"></span>' for i in s.other_ids)
            cards.append(
                f'  <div class="cz-card"{idattr} data-i="{len(texts) - 1}">{stray}\n'
                f'    <h3><a href="{href}">{html.escape(s.title)}</a></h3>\n'
                f'    <p class="cz-sum">{html.escape(s.summary)}</p>{subs}\n'
                "  </div>")
        intro = f'\n<p class="cz-intro">{p.intro}</p>' if p.intro else ""
        out.append(
            f'<section class="cz-group" id="{p.id}">\n'
            f'<h2><a href="{base}">{html.escape(p.title)}</a></h2>{intro}\n'
            '<div class="cz-cards">\n' + "\n".join(cards) + "\n</div>\n</section>")
    return HUB_TEMPLATE.format(css=CSS, nav=nav_block(pages, None), groups="\n\n".join(out),
                               map=json_for_script(amap), text=json_for_script(texts))


