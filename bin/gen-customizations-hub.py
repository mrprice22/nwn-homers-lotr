class _Text(HTMLParser):
    """Visible text of an HTML fragment, whitespace-collapsed."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self._skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self._skip += 1
        elif tag in ("p", "li", "dt", "dd", "tr", "br", "h3", "h4", "div"):
            self.parts.append(" ")

    def handle_endtag(self, tag):
        if tag in ("style", "script") and self._skip:
            self._skip -= 1
        elif tag in ("td", "th"):
            self.parts.append(" ")

    def handle_data(self, data):
        if not self._skip:
            self.parts.append(data)


def text_of(fragment: str) -> str:
    p = _Text()
    p.feed(re.sub(r"<!--.*?-->", " ", fragment, flags=re.S))
    p.close()
    return re.sub(r"\s+", " ", "".join(p.parts)).strip()


def clip(text: str, n: int = SUMMARY_CHARS) -> str:
    if len(text) <= n:
        return text
    cut = text[:n].rsplit(" ", 1)[0].rstrip(",;:—-")
    return cut + "…"


@dataclass
class Section:
    id: str | None          # the h3's id (None for a page's lead-in card)
    title: str
    html: str               # the section's HTML, h3 included
    subs: list[tuple[str, str]] = field(default_factory=list)   # (h4 id, h4 text)
    other_ids: list[str] = field(default_factory=list)          # every other id inside

    @property
    def text(self) -> str:
        return text_of(self.html)

    @property
    def summary(self) -> str:
        m = re.search(r"<p[^>]*>(.*?)</p>", self.html, re.S)
        return clip(text_of(m.group(1)) if m else self.text)


@dataclass
class Page:
    path: Path
    stem: str
    title: str
    order: int
    id: str                 # the h1's id (the old group anchor)
    heading: str            # h1 inner HTML
    intro: str              # cz-intro inner HTML, may be ""
    sections: list[Section]

    @property
    def href(self) -> str:
        return f"{self.stem}.html"


RE_BLOCK = {name: re.compile(rf"<!-- cz:{name} -->.*?<!-- /cz:{name} -->", re.S)
            for name in ("style", "nav", "crumb")}
RE_CONTENT = re.compile(r"<!-- /cz:crumb -->(.*?)</div><!-- \.mw-content -->", re.S)


def die(msg: str) -> None:
    print(f"gen-customizations-hub: {msg}", file=sys.stderr)
    sys.exit(2)


def load_page(path: Path) -> Page:
    raw = path.read_text(encoding="utf-8")
    for name, rx in RE_BLOCK.items():
        if not rx.search(raw):
            die(f"{path.name}: missing the <!-- cz:{name} --><!-- /cz:{name} --> block")
    title = re.search(r"<title>(.*?)</title>", raw, re.S)
    order = re.search(r'<meta name="cz-order" content="(\d+)"', raw)
    content = RE_CONTENT.search(raw)
    if not (title and content):
        die(f"{path.name}: needs a <title> and the '</div><!-- .mw-content -->' closer")
    content = content.group(1)
    h1 = re.search(r'<h1 id="([^"]+)">(.*?)</h1>', content, re.S)
    if not h1:
        die(f'{path.name}: the page heading must be <h1 id="...">')
    intro = re.search(r'<p class="cz-intro">(.*?)</p>', content, re.S)
    body = content[h1.end():]
    if intro:
        body = body.replace(intro.group(0), "", 1)

    sections: list[Section] = []
    parts = re.split(r"(?=<h3[\s>])", body)
    lead, rest = parts[0], parts[1:]
    if text_of(lead):
        sections.append(Section(None, "Overview" if rest else html.unescape(text_of(title.group(1))),
                                lead))
    for chunk in rest:
        m = re.match(r'<h3 id="([^"]+)"[^>]*>(.*?)</h3>', chunk, re.S)
        if not m:
            die(f"{path.name}: every <h3> needs an id -- '{text_of(chunk)[:60]}'")
        sections.append(Section(m.group(1), text_of(m.group(2)), chunk))
    for s in sections:
        for m in re.finditer(r'<h4 id="([^"]+)"[^>]*>(.*?)</h4>', s.html, re.S):
            s.subs.append((m.group(1), text_of(m.group(2))))
        sub_ids = {sid for sid, _ in s.subs}
        s.other_ids = [i for i in re.findall(r'\bid="([^"]+)"', s.html)
                       if i != s.id and i not in sub_ids]

    return Page(path, path.stem, html.unescape(title.group(1).strip()),
                int(order.group(1)) if order else 10**6, h1.group(1), h1.group(2).strip(),
                intro.group(1).strip() if intro else "", sections)


def load_pages() -> list[Page]:
    pages = [load_page(p) for p in sorted(TOPIC_DIR.glob("*.html"))]
    if not pages:
        die(f"no topic pages in {TOPIC_DIR}")
    pages.sort(key=lambda p: (p.order, p.stem))
    return pages


def anchor_map(pages: list[Page]) -> dict[str, str]:
    """Every id on every topic page -> its URL relative to the hub."""
    where: dict[str, str] = {}
    for p in pages:
        ids = [p.id] + [i for s in p.sections
                        for i in ([s.id] if s.id else []) + [x for x, _ in s.subs] + s.other_ids]
        for i in ids:
            if i in where:
                die(f"id '{i}' is used on two topic pages ({where[i]} and {p.stem}) -- "
                    "ids must be unique across the whole Customizations set")
            where[i] = f"Customizations/{p.href}" + ("" if i == p.id else f"#{i}")
    for old, new in ALIASES.items():
        if new not in where:
            die(f"ALIASES['{old}'] -> '{new}', which no topic page defines")
        where.setdefault(old, where[new])
    return where


# ---------------------------------------------------------------- topic-page blocks

def nav_block(pages: list[Page], here: Page | None) -> str:
    """Left-pane nav: every topic page, the current one expanded to its sections.
    `here` None = the hub, where links point into the folder."""
    pre = "" if here else "Customizations/"
    search = "../Customizations.html" if here else "#cz-q"
    rows = []
    for p in pages:
        cls = ' class="cz-here"' if p is here else ""
        link = f'<a href="{pre}{p.href}">{html.escape(p.title)}</a>'
        kids = ""
        items = [f'<li><a href="#{s.id}">{html.escape(s.title)}</a></li>'
                 for s in p.sections if s.id]
        if p is here and items:
            kids = "\n        <ol>\n          " + "\n          ".join(items) + "\n        </ol>"
        rows.append(f"      <li{cls}>{link}{kids}</li>")
    return (
        "<!-- cz:nav -->\n"
        '    <nav class="toc" aria-label="Customizations">\n'
        "      <h2>Customizations</h2>\n"
        f'      <p class="cz-navsearch"><a href="{search}">&#128269; Search every customization</a></p>\n'
        "      <ol>\n" + "\n".join(rows) + "\n      </ol>\n"
        "    </nav>\n"
        "  <!-- /cz:nav -->"
    )


def crumb_block(page: Page) -> str:
    return ('<!-- cz:crumb -->\n'
            '  <p class="cz-crumb"><a href="../Customizations.html">&larr; All customizations</a>'
            f' &middot; {html.escape(page.title)}</p>\n'
            '  <!-- /cz:crumb -->')


def style_block() -> str:
    return "<!-- cz:style -->\n  <style>" + CSS + "  </style>\n  <!-- /cz:style -->"


def render_topic(page: Page, pages: list[Page]) -> str:
    raw = page.path.read_text(encoding="utf-8")
    blocks = {"style": style_block(), "nav": nav_block(pages, page), "crumb": crumb_block(page)}
    for name, rx in RE_BLOCK.items():
        raw = rx.sub(lambda _m, b=blocks[name]: b, raw, count=1)
    return raw


