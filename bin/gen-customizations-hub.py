#!/usr/bin/env python3
"""gen-customizations-hub.py - build the player Customizations hub from its topic pages.

WHAT IT OWNS
------------
The player-facing reference for "what does this server do differently" used to be
one 115 KB page, docs.manual/Customizations.html. It is now:

  docs.manual/Customizations/<Topic>.html   hand-edited topic pages (one per group)
  docs.manual/Customizations.html           the hub -- GENERATED by this script

The hub carries a search box over the full text of every section, a card per
section, and a table of contents. This script also owns three marked blocks in
every topic page -- `<!-- cz:style -->`, `<!-- cz:nav -->` and `<!-- cz:crumb -->`
-- so the shared CSS and the cross-page navigation are written once, here, and a
section added to a topic page shows up in every nav and in search on the next run.

Edit the content of a topic page, never the hub or the cz: blocks, then run this.

OLD LINKS KEEP WORKING
----------------------
Players, Discord posts, roadmap.yaml and even an in-game string link to
`Customizations.html#<anchor>`. Every such anchor still resolves:

  * with JavaScript: the hub looks the hash up in its map and `location.replace`s
    to `Customizations/<Topic>.html#<anchor>`;
  * without it: every card / group / sub-link on the hub carries the same id, so the
    browser scrolls to the card, which links onward.

Every id ever published is recorded in ANCHORS_FILE (a ratchet: new ids are appended
on each write, never removed). If a recorded id disappears from the topic pages the
run FAILS -- keep the id, or add it to ALIASES pointing at its new home. Renaming a
section's id without that silently breaks every link anyone ever shared to it.

A topic page's position comes from `<meta name="cz-order" content="N">` in its head
(lower first); its nav title from `<title>`.

Usage:
    python3 bin/gen-customizations-hub.py            # write hub + refresh topic pages
    python3 bin/gen-customizations-hub.py --check    # exit 1 if anything is stale
                                                     # (tests/check_customizations_hub.py)

This is not the wiki refresh -- it only rewrites files under docs.manual/. Commit the
result; the daily refresh publishes it.
"""
