def read_anchor_ratchet() -> list[str]:
    if not ANCHORS_FILE.exists():
        return []
    return [l.strip() for l in ANCHORS_FILE.read_text(encoding="utf-8").splitlines()
            if l.strip() and not l.startswith("#")]


ANCHORS_HEADER = """\
# Every anchor ever published on the player Customizations pages. Old links to
# Customizations.html#<anchor> must keep resolving, so this list only grows.
# Appended by bin/gen-customizations-hub.py; checked by tests/check_customizations_hub.py.
# To retire an anchor, map it to its new home in ALIASES in that script -- never delete it here.
"""


def build(check: bool) -> int:
    pages = load_pages()
    amap = anchor_map(pages)

    recorded = read_anchor_ratchet()
    lost = [a for a in recorded if a not in amap]
    if lost:
        print("gen-customizations-hub: these published anchors no longer resolve -- every link "
              "anyone shared to them would break:\n  " + "\n  ".join(lost) +
              "\nRestore the id on its topic page, or map it in ALIASES in "
              "bin/gen-customizations-hub.py.", file=sys.stderr)
        return 1
    anchors = recorded + [a for a in amap if a not in recorded]
    anchors_text = ANCHORS_HEADER + "".join(f"{a}\n" for a in anchors)

    wanted = {HUB: render_hub(pages, amap), ANCHORS_FILE: anchors_text}
    for p in pages:
        wanted[p.path] = render_topic(p, pages)

    stale = [path for path, text in wanted.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            print("gen-customizations-hub: out of date -- run python3 bin/gen-customizations-hub.py:\n  "
                  + "\n  ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        print(f"gen-customizations-hub: OK ({len(pages)} topic pages, "
              f"{sum(len(p.sections) for p in pages)} sections, {len(amap)} anchors)")
        return 0
    for path in stale:
        path.write_text(wanted[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    if not stale:
        print("gen-customizations-hub: already up to date")
    return 0


