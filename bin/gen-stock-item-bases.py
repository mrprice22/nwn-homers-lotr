#!/usr/bin/env python3
"""Build tests/stock_item_bases.json — stock item resref -> BaseItem, for the
base items the stock AI's combat-start equip treats specially.

tests/check_creature_combat_gear.py replays x0_i0_equip.nss bkEquipMelee over
every creature blueprint, and that routine only cares whether an inventory item
is a single-handed weapon (x0_i0_match MatchSingleHandedWeapon) or a shield
(MatchShield). For a module item the answer is in the local `.uti`; for a stock
item (base game, in the install's BIF archives) there is no file in `unpacked/`.
A build gate must not depend on a local NWN install, so this writes a small
committed table: only stock resrefs whose BaseItem is one of those two sets are
recorded, and anything absent is "neither".

Re-run after a Beamdog patch that changes item blueprints:

    python3 bin/gen-stock-item-bases.py [--nwn /path/to/nwn]

Same KEY/BIF reader as bin/gen-stock-item-stacks.py.
"""

import argparse
import importlib.util
import json
import os
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "stock_item_bases.json"
sys.path.insert(0, str(ROOT / "tests"))
from check_creature_combat_gear import SHIELDS, SINGLE_HANDED  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "gen_stock_item_stacks", ROOT / "bin" / "gen-stock-item-stacks.py")
S = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(S)


def gff_base_item(data):
    """BaseItem out of a GFF V3.2 blob, or None. Top-level INT field."""
    try:
        _so, _sc, fo, fc, lo, lc, _fdo, _fdc = struct.unpack_from("<8I", data, 8)
        labels = [data[lo + 16 * i:lo + 16 * i + 16].rstrip(b"\0").decode("latin1")
                  for i in range(lc)]
        for i in range(fc):
            _t, li, dv = struct.unpack_from("<IIi", data, fo + 12 * i)
            if labels[li] == "BaseItem":
                return dv
    except (struct.error, IndexError, UnicodeDecodeError):
        return None
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nwn", type=Path, default=S.DEFAULT_NWN,
                    help=f"NWN install root (default: {S.DEFAULT_NWN})")
    args = ap.parse_args()

    sys.path.insert(0, str(S.WIKI_DATA))
    try:
        import build_stock_item_names as B
    except ImportError:
        print(f"error: cannot import the KEY/BIF reader from {S.WIKI_DATA} "
              "(nwn_manager repo)", file=sys.stderr)
        return 2

    keys = sorted((args.nwn / "data").glob("*.key"))
    if not keys:
        print(f"error: no .key archives under {args.nwn / 'data'}", file=sys.stderr)
        return 2

    index = {}
    for k in keys:
        index.update(B._parse_nwn_key(k))

    wanted = SINGLE_HANDED | SHIELDS
    bases = {}
    for resref in sorted(index):
        bif, var = index[resref]
        base = gff_base_item(B._read_bif_entry(bif, var))
        if base in wanted:
            bases[resref] = base

    OUT.write_text(json.dumps({
        "_comment": ("Stock (base game) item resref -> BaseItem, only for single-handed "
                     "weapons and shields as x0_i0_match.nss defines them. Generated by "
                     "bin/gen-stock-item-bases.py; consumed by "
                     "tests/check_creature_combat_gear.py. Anything absent is neither."),
        "_source": [k.name for k in keys],
        "bases": bases,
    }, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(bases)} stock weapon/shield "
          f"item(s) out of {len(index)} scanned")
    return 0


if __name__ == "__main__":
    sys.exit(main())
