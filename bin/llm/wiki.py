"""Read resolved data back out of the generated wiki under docs/.

Item property IDs in unpacked/*.uti.json are raw numbers -- `PropertyName: 0,
Subtype: 5, CostValue: 7` -- and nothing in bin/ resolves them to text; every
existing tool works numerically. The wiki generator already does the resolution
and writes it into docs/items/<resref>.html as a Properties table, so this reads
that back rather than adding a second 2DA resolver to maintain.

docs/ is volatile (fully regenerated by `nwn-manager wiki`) but it is committed,
and reading it is fine -- only hand-EDITING it is forbidden. If it is stale, the
worst case is a missing property row on a brand-new blueprint.
"""
from __future__ import annotations

import html
import re
from pathlib import Path

if __package__ in (None, ""):
    import pathlib as _pathlib
    import sys as _sys
    _sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[1]))

from llm import config

_TABLE = re.compile(r"<table.*?</table>", re.S)
_TAG = re.compile(r"<[^>]+>")


def _cells(table_html: str) -> list[list[str]]:
    rows = []
    for row in re.findall(r"<tr.*?</tr>", table_html, re.S):
        cells = [html.unescape(_TAG.sub("", c)).strip()
                 for c in re.findall(r"<t[dh].*?</t[dh]>", row, re.S)]
        if any(cells):
            rows.append(cells)
    return rows


def item_properties(resref: str) -> str:
    """Human-readable property list, e.g.
    "Ability Bonus: Charisma +7; AC Bonus: +5; Cast Spell: Harm 1/Day".

    Empty string when the wiki has no page for this resref.
    """
    path = config.DOCS / "items" / f"{resref}.html"
    if not path.exists():
        return ""
    text = path.read_text(encoding="utf-8", errors="replace")
    for table in _TABLE.findall(text):
        rows = _cells(table)
        if not rows or "Property" not in rows[0]:
            continue
        out = []
        for row in rows[1:]:
            parts = [c for c in row if c and c != "-"]
            if not parts:
                continue
            out.append(parts[0] + (": " + " ".join(parts[1:]) if len(parts) > 1 else ""))
        return "; ".join(out)
    return ""
