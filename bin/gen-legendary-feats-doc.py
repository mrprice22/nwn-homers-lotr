#!/usr/bin/env python3
"""gen-legendary-feats-doc.py - the player page for Legendary Feats, from FEATS.

`FEATS` in bin/gen-legendary-feats.py is the single source of truth for every
legendary feat: it already drives the feat.2da rows, the TLK strings and the
picker's generated include. This script renders the same table as the player
reference page docs.manual/Customizations/LegendaryFeats.html, so the page lists
exactly the feats the picker offers - no more (the draft's unapproved proposals
never appear) and no fewer (a shipped feat cannot go undocumented).

It owns the page's head and its content region; the cz:style / cz:nav / cz:crumb
blocks belong to bin/gen-customizations-hub.py, which this script runs afterwards
so the hub's search index picks the page up in the same step.

Usage:
    python3 bin/gen-legendary-feats-doc.py           # write the page (+ refresh hub)
    python3 bin/gen-legendary-feats-doc.py --check   # exit 1 if the page is stale

Run it whenever FEATS changes (a new feat, a reworded description, a prerequisite).
tests/check_customizations_hub.py fails the repack until you do.
"""
import argparse
import html
import importlib.machinery
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs.manual" / "Customizations" / "LegendaryFeats.html"


def _load(name: str, filename: str):
    loader = importlib.machinery.SourceFileLoader(name, str(ROOT / "bin" / filename))
    spec = importlib.util.spec_from_loader(name, loader)
    mod = importlib.util.module_from_spec(spec)
    loader.exec_module(mod)
    return mod


feats_mod = _load("gen_legendary_feats", "gen-legendary-feats.py")
hub_mod = _load("gen_customizations_hub", "gen-customizations-hub.py")

E = html.escape

# Page position among the topic pages: right after Character Progression (70).
ORDER = 75

# What each implementation kind means to a player. Only kinds with something worth
# saying are listed; a feat of any other kind gets no extra line.
KIND_NOTE = {
    "raw_ability": "Raises your <strong>base</strong> score permanently. It is not a buff, "
                   "so it does not count against the item ability-bonus cap.",
}

# Section heading per FEATS category, where "<category> Feats" would read badly.
HEADINGS = {"Ability Scores": "Ability Score Feats"}

SKELETON = """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Legendary Feats</title>
  <meta name="cz-order" content="{order}">
  <link rel="stylesheet" href="../../assets/style.css">
</head>
<body>
  <main>
  <!-- @menu 'Documents' -->
  <!-- @order 2 -->
  <!--
    GENERATED by bin/gen-legendary-feats-doc.py from FEATS in
    bin/gen-legendary-feats.py -- do not edit; change the feat table and re-run.
    The cz: blocks belong to bin/gen-customizations-hub.py.
  -->
  <!-- cz:style --><!-- /cz:style -->
  <div class="mw-layout">
  <aside class="mw-toc-pane">
  <!-- cz:nav --><!-- /cz:nav -->
  </aside>
  <div class="mw-content">
  <!-- cz:crumb --><!-- /cz:crumb -->{content}</div><!-- .mw-content -->
  </div><!-- .mw-layout -->
  </main>
</body>
</html>
"""

RE_CONTENT = re.compile(r"(<!-- /cz:crumb -->)(.*?)(</div><!-- \.mw-content -->)", re.S)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def render_content() -> str:
    feats = feats_mod.FEATS
    categories: list[str] = []
    for f in feats:
        if f.category not in categories:
            categories.append(f.category)

    out = ["""

<h1 id="legendary-feats">Legendary Feats</h1>
<p class="cz-intro">Extra feats you choose at level&nbsp;60, <strong>on top of</strong> the normal
level-60 feat. This page lists every legendary feat currently in the game.</p>

<h3 id="legendary-feats-how">How you get them</h3>
<p>When you reach <strong>level&nbsp;60</strong>, a Legendary Feats window opens a few seconds after
the level-up finishes. How many you may choose depends on your classes:</p>
<table class="change-table">
  <tr><th>Character</th><th>Legendary picks</th></tr>
  <tr><td>More than one class</td><td>1</td></tr>
  <tr><td>A single class</td><td>2</td></tr>
  <tr><td>Pure Fighter</td><td>3</td></tr>
</table>
<ul>
  <li><strong>Didn't finish choosing?</strong> Your unspent picks wait for you. The window opens
  again every time you finish a rest.</li>
  <li><strong>Want to choose again?</strong> Talk to <em>Ping Pong</em> in the Well of Eru and
  ask to choose your legendary feats again. You get all of them back to re-pick, along with any
  ability points they gave, and your level doesn't change. You can't do this while shapeshifted.</li>
  <li><strong>Changing your classes resets them.</strong> If you relevel into a different class
  makeup, or drop below level&nbsp;60, your legendary feats are handed back and you choose again.
  Level drain does <em>not</em> cost you your feats.</li>
  <li>A feat greyed out in the window has a requirement you don't meet yet. The window shows your
  own number next to each requirement (for example, <em>BAB 35+ (you have 34)</em>).</li>
</ul>
"""]
    for cat in categories:
        members = [f for f in feats if f.category == cat]
        heading = HEADINGS.get(cat, f"{cat} Feats")
        out.append(f'\n<h3 id="legendary-feats-{slug(cat)}">{E(heading)}</h3>\n')
        # A note every feat in the section shares is said once, under the heading.
        kinds = {f.kind for f in members}
        shared = KIND_NOTE.get(kinds.pop()) if len(kinds) == 1 else None
        if shared:
            out.append(f'<p class="cz-intro">{shared}</p>\n')
        for f in members:
            reqs = ", ".join(E(r.text()) for r in f.reqs) or "None"
            note = None if shared else KIND_NOTE.get(f.kind)
            out.append(
                f'<h4 id="lf-{slug(f.name)}">{E(f.name)}</h4>\n'
                f'<p>{E(f.description)}</p>\n'
                f'<p class="cz-intro"><strong>In short:</strong> {E(f.effect)}'
                f' &middot; <strong>Requires:</strong> {reqs}</p>\n'
                + (f'<p class="cz-intro">{note}</p>\n' if note else ""))
    out.append("\n  ")
    return "".join(out)


def wanted_page(current: str | None) -> str:
    content = render_content()
    if current is None or not RE_CONTENT.search(current):
        return SKELETON.format(order=ORDER, content=content)
    return RE_CONTENT.sub(lambda m: m.group(1) + content + m.group(3), current, count=1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if the page no longer matches FEATS")
    check = ap.parse_args().check

    current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else None
    want = wanted_page(current)
    if check:
        if current is None or RE_CONTENT.search(current) is None or \
                RE_CONTENT.search(current).group(2) != render_content():
            print("gen-legendary-feats-doc: docs.manual/Customizations/LegendaryFeats.html does "
                  "not match FEATS -- run python3 bin/gen-legendary-feats-doc.py", file=sys.stderr)
            return 1
        print(f"gen-legendary-feats-doc: OK ({len(feats_mod.FEATS)} feats)")
        return 0
    if want != current:
        PAGE.write_text(want, encoding="utf-8")
        print(f"wrote {PAGE.relative_to(ROOT)}")
    return hub_mod.build(check=False)


if __name__ == "__main__":
    sys.exit(main())
